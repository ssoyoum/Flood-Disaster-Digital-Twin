"""Facility registry: the hand-kept operational entries and the generated candidate list.

Two JSON files under data/facilities/ feed the twin:

- registry.json  — hand-maintained. OPERATIONAL facilities with their gauge, official levels, control
  rule, reference event and the four registration gates (all confirmed or explicitly MISSING).
- candidates.json — generated by data/scripts/build_facility_candidates.py from the public underpass
  catalog and the gauge links. CANDIDATE facilities carry nearby gauges and gate statuses but never a
  gauge, control rule or reference event: thresholds are registered per facility, never copied.

Validation is plain Python so a wrong entry fails at import with the facility and field named.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
FACILITIES_DIR = REPO_ROOT / "data" / "facilities"
REGISTRY_FILE = FACILITIES_DIR / "registry.json"
CANDIDATES_FILE = FACILITIES_DIR / "candidates.json"

GATE_IDS = ("inflow_path", "representative_gauge", "site_instrumentation", "validation_event")
GATE_STATUSES = ("CONFIRMED", "PENDING", "MISSING", "UNKNOWN")
FACILITY_STATUSES = ("OPERATIONAL", "CANDIDATE")
LEVEL_KEYS = ("attention", "advisory", "warning", "severe", "planned_flood")
# A candidate must not carry any of these: that is how a threshold would sneak in before the gates are met.
CANDIDATE_FORBIDDEN = ("gauge", "control_rule", "reference_event")


def _fail(facility: dict[str, Any], field: str, why: str) -> ValueError:
    return ValueError(f"facility registry: {facility.get('id') or facility.get('name') or '<no id>'}: {field}: {why}")


def validate_gates(facility: dict[str, Any], *, allow_unknown: bool) -> None:
    gates = facility.get("gates")
    if not isinstance(gates, dict):
        raise _fail(facility, "gates", "must be an object with the four gate ids")
    for gate_id in GATE_IDS:
        gate = gates.get(gate_id)
        if not isinstance(gate, dict) or gate.get("status") not in GATE_STATUSES:
            raise _fail(facility, f"gates.{gate_id}", f"status must be one of {', '.join(GATE_STATUSES)}")
        if not allow_unknown and gate["status"] == "UNKNOWN":
            raise _fail(facility, f"gates.{gate_id}", "an OPERATIONAL facility may not leave a gate UNKNOWN (confirm it or mark it MISSING)")
    extra = set(gates) - set(GATE_IDS)
    if extra:
        raise _fail(facility, "gates", f"unknown gate ids: {', '.join(sorted(extra))}")


def validate_operational(facility: dict[str, Any]) -> None:
    for field in ("id", "name", "kind", "driver", "location", "control_rule", "reference_event", "event_id"):
        if not facility.get(field):
            raise _fail(facility, field, "required for an OPERATIONAL facility")
    location = facility["location"]
    if not (isinstance(location, list) and len(location) == 2 and all(isinstance(v, (int, float)) for v in location)):
        raise _fail(facility, "location", "must be [lon, lat]")
    gauge = facility.get("gauge")
    if not isinstance(gauge, dict) or not gauge.get("station_id"):
        raise _fail(facility, "gauge", "required with a station_id")
    levels = gauge.get("levels_m")
    if not isinstance(levels, dict):
        raise _fail(facility, "gauge.levels_m", "required")
    missing = [k for k in LEVEL_KEYS if not isinstance(levels.get(k), (int, float))]
    if missing:
        raise _fail(facility, "gauge.levels_m", f"missing numeric levels: {', '.join(missing)}")
    rule = facility["control_rule"]
    for field in ("id", "rate_window_min", "lead_threshold_min"):
        if rule.get(field) is None:
            raise _fail(facility, f"control_rule.{field}", "required")
    validate_gates(facility, allow_unknown=False)


def validate_candidate(facility: dict[str, Any]) -> None:
    for field in ("id", "name", "region", "source"):
        if not facility.get(field):
            raise _fail(facility, field, "required for a CANDIDATE facility")
    for field in CANDIDATE_FORBIDDEN:
        if facility.get(field) is not None:
            raise _fail(facility, field, "a CANDIDATE may not carry a gauge, control rule or reference event; register it per facility once the gates are confirmed")
    location = facility.get("location")
    if location is not None and not (isinstance(location, list) and len(location) == 2):
        raise _fail(facility, "location", "must be [lon, lat] or null")
    if not isinstance(facility.get("nearby_gauges", []), list):
        raise _fail(facility, "nearby_gauges", "must be a list")
    if not isinstance(facility.get("nearby_rain_gauges", []), list):
        raise _fail(facility, "nearby_rain_gauges", "must be a list")
    hypothesis = facility.get("driver_hypothesis")
    if hypothesis is not None and hypothesis not in ("river", "pluvial"):
        raise _fail(facility, "driver_hypothesis", "must be river, pluvial or omitted")
    if hypothesis and facility.get("driver") != "unverified":
        raise _fail(facility, "driver", "a CANDIDATE driver hypothesis may not be presented as verified")
    validate_gates(facility, allow_unknown=True)


def validate_facility(facility: dict[str, Any]) -> None:
    status = facility.get("status")
    if status not in FACILITY_STATUSES:
        raise _fail(facility, "status", f"must be one of {', '.join(FACILITY_STATUSES)}")
    if status == "OPERATIONAL":
        validate_operational(facility)
    else:
        validate_candidate(facility)


def _read(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"facility registry file missing: {path}")
    return json.loads(path.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def _load() -> dict[str, Any]:
    registry = _read(REGISTRY_FILE)
    gates = registry.get("gates") or []
    if [g.get("id") for g in gates] != list(GATE_IDS):
        raise ValueError(f"facility registry: gates must be exactly {', '.join(GATE_IDS)} in order")
    operational: dict[str, dict[str, Any]] = {}
    for facility in registry.get("facilities", []):
        validate_facility(facility)
        if facility["status"] != "OPERATIONAL":
            raise _fail(facility, "status", "registry.json holds OPERATIONAL facilities only; candidates belong in candidates.json")
        if facility["id"] in operational:
            raise _fail(facility, "id", "duplicate")
        operational[facility["id"]] = facility
    candidates: list[dict[str, Any]] = []
    if CANDIDATES_FILE.exists():
        for facility in _read(CANDIDATES_FILE).get("candidates", []):
            validate_facility(facility)
            if facility["status"] != "CANDIDATE":
                raise _fail(facility, "status", "candidates.json holds CANDIDATE facilities only")
            if facility["id"] in operational or any(c["id"] == facility["id"] for c in candidates):
                raise _fail(facility, "id", "duplicate")
            candidates.append(facility)
    return {"gates": gates, "operational": operational, "candidates": candidates}


def gate_definitions() -> list[dict[str, Any]]:
    return list(_load()["gates"])


def operational() -> dict[str, dict[str, Any]]:
    """Facility id → full entry, in registry order. Same shape ``twin.FACILITIES`` always had."""

    return _load()["operational"]


def candidates() -> list[dict[str, Any]]:
    return list(_load()["candidates"])


def get(facility_id: str) -> dict[str, Any] | None:
    data = _load()
    if facility_id in data["operational"]:
        return data["operational"][facility_id]
    return next((c for c in data["candidates"] if c["id"] == facility_id), None)


def unmet_gates(facility: dict[str, Any]) -> list[str]:
    return [gate_id for gate_id in GATE_IDS if facility.get("gates", {}).get(gate_id, {}).get("status") != "CONFIRMED"]


def summary(facility: dict[str, Any]) -> dict[str, Any]:
    """Status, gates and identity only; thresholds and rules stay behind the per-facility endpoints."""

    gauge = facility.get("gauge")
    return {
        **{k: facility.get(k) for k in ("id", "name", "kind", "driver", "status", "region", "location", "road", "managing_agency", "event_id")},
        "gauge": {"station_id": gauge["station_id"], "name": gauge["name"]} if gauge else None,
        "gates": facility.get("gates", {}),
        "unmet_gates": unmet_gates(facility),
    }


def registry_payload() -> dict[str, Any]:
    data = _load()
    return {
        "gates": list(data["gates"]),
        "operational": [summary(f) for f in data["operational"].values()],
        "candidates": [{**c, "unmet_gates": unmet_gates(c)} for c in data["candidates"]],
        "counts": {"operational": len(data["operational"]), "candidate": len(data["candidates"])},
    }
